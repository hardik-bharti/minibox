// errUsage means the usage text has been printed; exit with status 2.
var errUsage = errors.New("usage")

// runFlags holds the parsed `minibox run` command line.
type runFlags struct {
	hostname string
	memory   string
	limits   cgroups.Limits
	stats    bool
	net      network.Mode
	ports    portList
	volumes  volumeList
	security security.Config
	output   string // profile only: where to write the policy
	merge    bool   // profile only: union with the existing policy file
	rootfs   string
	command  []string
}

// portList collects repeated -p flags.
type portList []network.Port

func (l *portList) String() string { return fmt.Sprint(*l) }

func (l *portList) Set(s string) error {
	p, err := network.ParsePort(s)
	if err != nil {
		return err
	}
	*l = append(*l, p)
	return nil
}

// volumeList collects repeated -v flags.
type volumeList []container.Volume

func (l *volumeList) String() string { return fmt.Sprint(*l) }

func (l *volumeList) Set(s string) error {
	v, err := container.ParseVolume(s)
	if err != nil {
		return err
	}
	*l = append(*l, v)
	return nil
}

// parseRunFlags parses `minibox run [flags] <rootfs> <cmd> [args...]`.
// `minibox profile` takes the same flags, except that -o replaces
// --security/--policy (profiling always runs unrestricted).
//
// Go's flag package stops at the first non-flag argument, so flags must come
// before <rootfs>. That is what we want: in `minibox run img ls -l`, the -l
// belongs to ls, not to us.
func parseRunFlags(name string, args []string, stderr io.Writer) (*runFlags, error) {
	f := &runFlags{}
	fs := flag.NewFlagSet(name, flag.ContinueOnError)
	fs.SetOutput(stderr)
	fs.StringVar(&f.hostname, "hostname", "", "container hostname (default: container ID)")
	fs.StringVar(&f.memory, "memory", "", "memory limit, e.g. 64m or 1g (swap is disabled)")
	fs.Float64Var(&f.limits.CPUs, "cpus", 0, "CPU limit in CPUs, e.g. 0.5 (default: unlimited)")
	fs.Int64Var(&f.limits.Pids, "pids", 0, "maximum number of processes (default: unlimited)")
	fs.BoolVar(&f.stats, "stats", false, "print cgroup resource usage to stderr on exit")
	netMode := fs.String("net", "none", "network: none (loopback only) or bridge (outbound access via slirp4netns)")
	fs.Var(&f.ports, "p", "publish a port, HOST:CONTAINER[/tcp|udp] (repeatable, needs --net=bridge)")
	fs.Var(&f.ports, "publish", "same as -p")
	fs.Var(&f.volumes, "v", "bind-mount a host directory, HOST:CONTAINER[:ro] (repeatable)")
	secMode, policyPath := new(string), new(string)
	if name == "profile" {
		fs.StringVar(&f.output, "o", "policy.json", "write the generated policy to this file")
		fs.BoolVar(&f.merge, "merge", false, "merge with the policy already in the -o file (union), to combine several runs")
	} else {
		fs.StringVar(secMode, "security", "baseline", "hardening: baseline (Docker-like defaults) or none")
		fs.StringVar(policyPath, "policy", "", "enforce a policy file generated by `minibox profile` (least privilege)")
	}
	fs.Usage = func() {
		fmt.Fprintf(stderr, "Usage: minibox %s [flags] <rootfs> <cmd> [args...]\n", name)
		fs.PrintDefaults()
	}
	if err := fs.Parse(args); err != nil {
		return nil, errUsage // flag has already printed the problem and usage
	}
	if fs.NArg() < 2 {
		fs.Usage()
		return nil, errUsage
	}
	if f.memory != "" {
		n, err := cgroups.ParseMemory(f.memory)
		if err != nil {
			return nil, err
		}
		f.limits.MemoryBytes = n
	}
	if err := f.limits.Validate(); err != nil {
		return nil, err
	}
	var err error
	if f.net, err = network.ParseMode(*netMode); err != nil {
		return nil, err
	}
	if len(f.ports) > 0 && f.net != network.Bridge {
		return nil, errors.New("-p needs --net=bridge (with --net=none there is nothing to forward to)")
	}
	if f.security, err = parseSecurity(*secMode, *policyPath, fs); err != nil {
		return nil, err
	}
	f.rootfs, f.command = fs.Arg(0), fs.Args()[1:]
	return f, nil
}

// parseSecurity combines --security and --policy into one configuration.
func parseSecurity(mode, policyPath string, fs *flag.FlagSet) (security.Config, error) {
	m, err := security.ParseMode(mode)
	if err != nil {
		return security.Config{}, err
	}
	if policyPath == "" {
		if m == security.None {
			return security.Config{Mode: security.None}, nil
		}
		return security.NewBaseline(), nil
	}
	securitySet := false
	fs.Visit(func(fl *flag.Flag) { securitySet = securitySet || fl.Name == "security" })
	if securitySet {
		return security.Config{}, errors.New("--policy and --security are mutually exclusive")
	}
	p, err := security.LoadPolicy(policyPath)
	if err != nil {
		return security.Config{}, err
	}
	return security.NewFromPolicy(p), nil
}

// cmdRun implements `minibox run`.
func cmdRun(args []string, stderr io.Writer) int {
	return runOrProfile("run", args, stderr)
}

// cmdProfile implements `minibox profile`: run the command under a tracer
// and write a least-privilege policy for it.
func cmdProfile(args []string, stderr io.Writer) int {
	return runOrProfile("profile", args, stderr)
}

func runOrProfile(name string, args []string, stderr io.Writer) int {
	f, err := parseRunFlags(name, args, stderr)
	if errors.Is(err, errUsage) {
		return 2
	} else if err != nil {
		return fail(stderr, err)
	}

	// --stats needs a cgroup too, even without limits.
	needCgroup := !f.limits.IsZero() || f.stats
	if needCgroup {
		if ok, err := cgroups.Delegated(); err != nil {
			return fail(stderr, err)
		} else if !ok {
			return fail(stderr, reexecInScope(name, args))
		}
	}

	stateRoot, err := container.DefaultStateRoot()
	if err != nil {
		return fail(stderr, err)
	}
	cfg, err := container.NewConfig(f.rootfs, f.command, f.hostname, stateRoot)
	if err != nil {
		return fail(stderr, err)
	}
	cfg.Limits = f.limits
	cfg.WantCgroup = needCgroup
	cfg.Net = f.net
	cfg.Ports = f.ports
	cfg.Volumes = f.volumes
	cfg.Security = f.security

	if name == "profile" {
		return profileContainer(cfg, f, stderr)
	}
	res, err := container.Run(cfg)
	if err != nil {
		return fail(stderr, err)
	}
	reportStats(stderr, f, res)
	return res.ExitCode
}

// profileContainer runs cfg under the tracer and saves the policy. The
// policy is written even if the command fails: a server stopped with
// Ctrl-C exits non-zero, and that is the normal way to end a profile.
func profileContainer(cfg *container.Config, f *runFlags, stderr io.Writer) int {
	res, pol, err := profile.Run(cfg)
	if err != nil {
		return fail(stderr, err)
	}
	reportStats(stderr, f, res)
	for _, w := range pol.Warnings {
		fmt.Fprintf(stderr, "minibox profile: warning: %s\n", w)
	}
	if f.merge {
		if old, err := security.LoadPolicy(f.output); err == nil {
			pol = profile.Merge(old, pol)
		} else if !errors.Is(err, os.ErrNotExist) {
			return fail(stderr, fmt.Errorf("--merge: %w", err))
		}
	}
	if err := pol.Save(f.output); err != nil {
		return fail(stderr, err)
	}
	fmt.Fprintf(stderr, "minibox profile: %d syscalls, %d capabilities %v, %d writable paths %v -> %s\n",
		len(pol.Syscalls), len(pol.Capabilities), pol.Capabilities,
		len(pol.WritablePaths), pol.WritablePaths, f.output)
	return res.ExitCode
}

// scopeEnv marks a minibox that has already been re-executed by systemd-run,
// so a misconfigured system produces an error instead of an endless loop.
const scopeEnv = "MINIBOX_IN_SCOPE"

// reexecInScope replaces this process with
//
//	systemd-run --user --scope -p Delegate=yes -- minibox run <args>
//
// A login shell's cgroup (session-N.scope) belongs to root, so we may not
// create cgroups there. Asking our per-user systemd for a transient scope
// with Delegate=yes gives us a cgroup we own. systemd removes the scope when
// we exit. We use exec rather than a child process so the terminal, signals
// and exit status pass straight through. It only returns on failure.
func reexecInScope(name string, args []string) error {
	if os.Getenv(scopeEnv) != "" {
		return fmt.Errorf("still not in a delegated cgroup after systemd-run; " +
			"check that 'systemctl --user' works and that cpu/memory/pids are delegated (scripts/check-env.sh)")
	}
	systemdRun, err := exec.LookPath("systemd-run")
	if err != nil {
		return fmt.Errorf("resource limits need systemd-run to get a delegated cgroup: %w", err)
	}
	self, err := os.Executable()
	if err != nil {
		return err
	}
	argv := append([]string{systemdRun, "--user", "--scope", "--quiet", "--collect",
		"-p", "Delegate=yes", "--", self, name}, args...)
	env := append(os.Environ(), scopeEnv+"=1")
	return syscall.Exec(systemdRun, argv, env)
}

// reportStats warns about limit hits (always) and prints full usage (--stats).
func reportStats(stderr io.Writer, f *runFlags, res container.Result) {
	if res.Stats == nil {
		return
	}
	if res.Stats.OOMKills > 0 {
		fmt.Fprintf(stderr, "minibox: %d process(es) killed for exceeding --memory %s\n",
			res.Stats.OOMKills, f.memory)
	}
	if res.Stats.PidsRejected > 0 {
		fmt.Fprintf(stderr, "minibox: %d fork(s) refused by --pids %d\n",
			res.Stats.PidsRejected, f.limits.Pids)
	}
	if f.stats {
		fmt.Fprintf(stderr, "minibox stats: %s\n", res.Stats)
	}
}

// cmdInit is the hidden entry point for the re-executed child process; see
// container.Init. It only returns if setup failed, since on success the
// process is replaced by the user's command.
func cmdInit(stderr io.Writer) int {
	err := container.Init()
	fmt.Fprintf(stderr, "minibox: container init: %v\n", err)
	// 127 (not 1) so a setup failure can be told apart from a command that
	// merely exited with status 1. Shells use 127 for "command not found".
	return 127
}

func fail(stderr io.Writer, err error) int {
	fmt.Fprintf(stderr, "minibox: %v\n", err)
	return 1
}
