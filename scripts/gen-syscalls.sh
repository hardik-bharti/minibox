#!/usr/bin/env bash
# gen-syscalls.sh: regenerate internal/security/syscalls_amd64.go, the
# syscall name <-> number table for x86_64, from the kernel UAPI header.
#
# seccomp filters and ptrace both deal in syscall *numbers*, while
# profiles (Docker's and ours) use *names*, so we need the mapping. We take
# it straight from the kernel's own header instead of typing it by hand.
set -euo pipefail
cd "$(dirname "$0")/.."

hdr=/usr/include/x86_64-linux-gnu/asm/unistd_64.h
[ -r "$hdr" ] || { echo "missing $hdr: sudo apt install linux-libc-dev" >&2; exit 1; }
out=internal/security/syscalls_amd64.go

{
    echo "// Code generated by scripts/gen-syscalls.sh from $hdr. DO NOT EDIT."
    echo
    echo "package security"
    echo
    echo "// syscallNumbers maps x86_64 syscall names to numbers."
    echo "var syscallNumbers = map[string]int{"
    awk '$1 == "#define" && $2 ~ /^__NR_/ { sub(/^__NR_/, "", $2); printf "\t\"%s\": %s,\n", $2, $3 }' "$hdr"
    echo "}"
} > "$out"
gofmt -w "$out"
echo "wrote $out ($(grep -c '": ' "$out") syscalls)"
